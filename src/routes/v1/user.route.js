const express = require('express');
// const auth = require('../../middlewares/auth');
const validate = require('../../middlewares/validate');
const userValidation = require('../../validations/user.validation');
const userController = require('../../controllers/user.controller');
const {
  softAuth,
  requireAuth,
  requireAdmin,
  requireSelfOrAdmin,
  scopeSubAgentUsers,
} = require('../../middlewares/subAgentScope');

const router = express.Router();

// A sub-agent may read the staff roster (the portal's @mention autocomplete)
// and read/update its OWN user record, and nothing else on this router.
// softAuth only identifies the caller; it never rejects one, so behaviour for
// every other role is unchanged.
router.use(softAuth, scopeSubAgentUsers);

/**
 * Creating a user was UNAUTHENTICATED and UNVALIDATED: no auth(), no validate(),
 * and the controller passed req.body straight to User.create. `role` is a
 * schema field, so any unauthenticated caller could create a user with an admin
 * role id -- remote admin-account creation against the public API.
 *
 * Now: a real admin session, and the Joi schema (which also pins `role` to an
 * ObjectId and rejects unknown keys). Note the CRM does not refresh its access
 * token and it expires after 30 minutes, so an idle admin will get a 401 here
 * and must sign in again. That is the right failure: the alternative -- ignoring
 * `role` for unauthenticated callers -- would fall back to the User model's
 * default, which is itself an admin id.
 */
router
  .route('/')
  .post(requireAuth, requireAdmin, validate(userValidation.createUser), userController.createUser)
  .get(validate(userValidation.getUsers), userController.getUsers);
router.route('/users').get(userController.getUsersWithoutPagination);

/**
 * PATCH accepted `password` with no authentication at all, so anyone could
 * reset any account's password -- admins included -- and then sign in as them.
 * DELETE was equally open. GET stays as it is: the CRM reads user records on
 * screens that predate this and it exposes no credential (`password` is
 * `private` in the schema and stripped by toJSON).
 */
router
  .route('/:userId')
  .get(validate(userValidation.getUser), userController.getUser)
  .patch(requireAuth, requireSelfOrAdmin, validate(userValidation.updateUser), userController.updateUser)
  .delete(requireAuth, requireAdmin, validate(userValidation.deleteUser), userController.deleteUser);

module.exports = router;

